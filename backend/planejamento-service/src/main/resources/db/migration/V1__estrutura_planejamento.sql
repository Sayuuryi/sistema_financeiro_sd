CREATE TABLE despesa_prevista (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 pessoa_id BIGINT NOT NULL CHECK (pessoa_id > 0), pessoa_nome VARCHAR(120) NOT NULL,
 categoria_id BIGINT NOT NULL CHECK (categoria_id > 0), categoria_versao BIGINT NOT NULL,
 categoria_codigo VARCHAR(20) NOT NULL, categoria_nome VARCHAR(100) NOT NULL,
 categoria_natureza VARCHAR(20) NOT NULL CHECK (categoria_natureza='DESPESA'), categoria_ativo BOOLEAN NOT NULL,
 descricao VARCHAR(180) NOT NULL, referencia VARCHAR(60), data_prevista DATE NOT NULL,
 valor_previsto NUMERIC(19,2) NOT NULL CHECK (valor_previsto > 0),
 observacoes VARCHAR(1500), ativo BOOLEAN NOT NULL DEFAULT TRUE,
 conta_gerada_id BIGINT UNIQUE CHECK (conta_gerada_id > 0)
);
CREATE INDEX ix_previsao_data ON despesa_prevista(data_prevista);
