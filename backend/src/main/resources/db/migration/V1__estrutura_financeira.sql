CREATE TABLE pessoa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CLIENTE', 'FORNECEDOR', 'AMBOS')),
    documento VARCHAR(20) UNIQUE,
    email VARCHAR(150),
    telefone VARCHAR(30),
    contato VARCHAR(100),
    endereco VARCHAR(200),
    cidade VARCHAR(80),
    estado VARCHAR(2),
    cep VARCHAR(9),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nome VARCHAR(100) NOT NULL,
    natureza VARCHAR(20) NOT NULL CHECK (natureza IN ('RECEITA', 'DESPESA')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE banco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE agencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    banco_id BIGINT NOT NULL REFERENCES banco(id),
    numero VARCHAR(20) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_agencia UNIQUE (banco_id, numero)
);
CREATE TABLE conta_bancaria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    agencia_id BIGINT NOT NULL REFERENCES agencia(id),
    numero VARCHAR(30) NOT NULL,
    descricao VARCHAR(120) NOT NULL,
    saldo_inicial NUMERIC(19, 2) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_conta_bancaria UNIQUE (agencia_id, numero)
);
CREATE TABLE despesa_prevista (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    pessoa_id BIGINT NOT NULL REFERENCES pessoa(id),
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    descricao VARCHAR(180) NOT NULL,
    referencia VARCHAR(60),
    data_prevista DATE NOT NULL,
    valor_previsto NUMERIC(19, 2) NOT NULL CHECK (valor_previsto > 0),
    observacoes VARCHAR(1500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE conta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PAGAR', 'RECEBER')),
    pessoa_id BIGINT NOT NULL REFERENCES pessoa(id),
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    despesa_origem_id BIGINT UNIQUE REFERENCES despesa_prevista(id),
    numero_titulo VARCHAR(60) NOT NULL,
    tipo_titulo VARCHAR(30) NOT NULL CHECK (
        tipo_titulo IN ('DUPLICATA', 'NOTA_PROMISSORIA', 'OUTROS')
    ),
    descricao VARCHAR(180) NOT NULL,
    emissao DATE NOT NULL,
    vencimento DATE NOT NULL,
    valor NUMERIC(19, 2) NOT NULL CHECK (valor > 0),
    desconto_maximo NUMERIC(19, 2) NOT NULL DEFAULT 0 CHECK (
        desconto_maximo >= 0
        AND desconto_maximo <= valor
    ),
    validade_desconto DATE,
    observacoes VARCHAR(1500),
    cancelada BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_cancelamento VARCHAR(250),
    cancelada_em TIMESTAMP WITH TIME ZONE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_datas_conta CHECK (vencimento >= emissao),
    CONSTRAINT ck_desconto_data CHECK (
        desconto_maximo = 0
        OR validade_desconto IS NOT NULL
    ),
    CONSTRAINT uk_titulo UNIQUE (tipo, pessoa_id, numero_titulo)
);
CREATE TABLE baixa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    versao BIGINT NOT NULL DEFAULT 0,
    conta_id BIGINT NOT NULL REFERENCES conta(id),
    conta_bancaria_id BIGINT REFERENCES conta_bancaria(id),
    chave_idempotencia VARCHAR(36) NOT NULL UNIQUE,
    data DATE NOT NULL,
    principal NUMERIC(19, 2) NOT NULL CHECK (principal > 0),
    acrescimo NUMERIC(19, 2) NOT NULL DEFAULT 0 CHECK (acrescimo >= 0),
    desconto NUMERIC(19, 2) NOT NULL DEFAULT 0 CHECK (desconto >= 0),
    forma VARCHAR(25) NOT NULL CHECK (
        forma IN (
            'DINHEIRO',
            'PIX',
            'TRANSFERENCIA',
            'BOLETO',
            'CARTAO',
            'CHEQUE'
        )
    ),
    observacoes VARCHAR(1000),
    estornada BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_estorno VARCHAR(250),
    estornada_em TIMESTAMP WITH TIME ZONE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_baixa_liquida CHECK (principal + acrescimo - desconto > 0)
);
CREATE INDEX ix_conta_vencimento ON conta(vencimento);
CREATE INDEX ix_conta_pessoa ON conta(pessoa_id);
CREATE INDEX ix_conta_categoria ON conta(categoria_id);
CREATE INDEX ix_baixa_conta ON baixa(conta_id);
CREATE INDEX ix_baixa_data ON baixa(data);
CREATE INDEX ix_baixa_banco ON baixa(conta_bancaria_id);