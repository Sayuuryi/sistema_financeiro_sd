CREATE TABLE pessoa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 nome VARCHAR(120) NOT NULL,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CLIENTE','FORNECEDOR','AMBOS')),
 documento VARCHAR(20) UNIQUE,
 email VARCHAR(150), telefone VARCHAR(30), contato VARCHAR(100),
 endereco VARCHAR(200), cidade VARCHAR(80), estado VARCHAR(2), cep VARCHAR(9),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 excluido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE categoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 codigo VARCHAR(20) NOT NULL UNIQUE,
 nome VARCHAR(100) NOT NULL,
 natureza VARCHAR(20) NOT NULL CHECK (natureza IN ('RECEITA','DESPESA')),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 excluido BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE banco (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 codigo VARCHAR(10) NOT NULL UNIQUE, nome VARCHAR(120) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE agencia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 banco_id BIGINT NOT NULL REFERENCES banco(id),
 numero VARCHAR(20) NOT NULL, nome VARCHAR(120) NOT NULL,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_agencia UNIQUE (banco_id,numero)
);
CREATE TABLE conta_bancaria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 agencia_id BIGINT NOT NULL REFERENCES agencia(id),
 numero VARCHAR(30) NOT NULL, descricao VARCHAR(120) NOT NULL,
 saldo_inicial NUMERIC(19,2) NOT NULL DEFAULT 0,
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uk_conta_bancaria UNIQUE (agencia_id,numero),
 excluido BOOLEAN NOT NULL DEFAULT FALSE
);
