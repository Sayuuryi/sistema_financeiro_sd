CREATE TABLE usuario (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 nome VARCHAR(120) NOT NULL CHECK (length(trim(nome)) >= 2),
 email VARCHAR(160) NOT NULL UNIQUE CHECK (email = lower(email)),
 senha_hash VARCHAR(100) NOT NULL,
 telefone VARCHAR(30),
 cargo VARCHAR(80),
 empresa VARCHAR(120),
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 ultimo_acesso_em TIMESTAMP WITH TIME ZONE
);
CREATE TABLE sessao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
 token_hash CHAR(64) NOT NULL UNIQUE,
 criada_em TIMESTAMP WITH TIME ZONE NOT NULL,
 expira_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_sessao_usuario ON sessao(usuario_id);
CREATE INDEX ix_sessao_expira ON sessao(expira_em);
