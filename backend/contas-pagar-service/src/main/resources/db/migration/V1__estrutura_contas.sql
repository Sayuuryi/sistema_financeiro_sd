CREATE TABLE conta (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('PAGAR','RECEBER')),
 pessoa_id BIGINT NOT NULL CHECK (pessoa_id > 0),
 pessoa_nome VARCHAR(120) NOT NULL,
 categoria_id BIGINT NOT NULL CHECK (categoria_id > 0),
 categoria_versao BIGINT NOT NULL,
 categoria_codigo VARCHAR(20) NOT NULL,
 categoria_nome VARCHAR(100) NOT NULL,
 categoria_natureza VARCHAR(20) NOT NULL CHECK (categoria_natureza IN ('RECEITA','DESPESA')),
 categoria_ativo BOOLEAN NOT NULL,
 despesa_origem_id BIGINT UNIQUE CHECK (despesa_origem_id > 0),
 origem_hash VARCHAR(64),
 numero_titulo VARCHAR(60) NOT NULL,
 tipo_titulo VARCHAR(30) NOT NULL CHECK (tipo_titulo IN ('DUPLICATA','NOTA_PROMISSORIA','OUTROS')),
 descricao VARCHAR(180) NOT NULL,
 emissao DATE NOT NULL, vencimento DATE NOT NULL,
 valor NUMERIC(19,2) NOT NULL CHECK (valor > 0),
 desconto_maximo NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (desconto_maximo >= 0 AND desconto_maximo <= valor),
 validade_desconto DATE,
 observacoes VARCHAR(1500), cancelada BOOLEAN NOT NULL DEFAULT FALSE,
 motivo_cancelamento VARCHAR(250), cancelada_em TIMESTAMP WITH TIME ZONE,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT ck_origem_hash CHECK ((despesa_origem_id IS NULL AND origem_hash IS NULL) OR (despesa_origem_id IS NOT NULL AND origem_hash IS NOT NULL AND length(origem_hash)=64)),
 CONSTRAINT ck_datas_conta CHECK (vencimento >= emissao),
 CONSTRAINT ck_desconto_data CHECK (desconto_maximo = 0 OR validade_desconto IS NOT NULL),
 CONSTRAINT uk_titulo UNIQUE (tipo,pessoa_id,numero_titulo)
);
CREATE TABLE baixa (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 versao BIGINT NOT NULL DEFAULT 0,
 conta_id BIGINT NOT NULL REFERENCES conta(id),
 conta_bancaria_id BIGINT CHECK (conta_bancaria_id > 0),
 conta_bancaria_descricao VARCHAR(180),
 chave_idempotencia VARCHAR(36) NOT NULL UNIQUE,
 data DATE NOT NULL,
 principal NUMERIC(19,2) NOT NULL CHECK (principal > 0),
 acrescimo NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (acrescimo >= 0),
 desconto NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (desconto >= 0),
 forma VARCHAR(25) NOT NULL CHECK (forma IN ('DINHEIRO','PIX','TRANSFERENCIA','BOLETO','CARTAO','CHEQUE')),
 observacoes VARCHAR(1000), estornada BOOLEAN NOT NULL DEFAULT FALSE,
 motivo_estorno VARCHAR(250), estornada_em TIMESTAMP WITH TIME ZONE,
 criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT ck_baixa_liquida CHECK (principal + acrescimo - desconto > 0)
);
CREATE INDEX ix_conta_vencimento ON conta(vencimento);
CREATE INDEX ix_conta_pessoa ON conta(pessoa_id);
CREATE INDEX ix_conta_categoria ON conta(categoria_id);
CREATE INDEX ix_baixa_conta ON baixa(conta_id);
CREATE INDEX ix_baixa_data ON baixa(data);
CREATE INDEX ix_baixa_banco ON baixa(conta_bancaria_id);
